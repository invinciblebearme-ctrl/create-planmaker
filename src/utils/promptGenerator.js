import { CREATE_STAGES } from '../constants/createConfig';

export function generateCreatePrompt({
  stds = [],
  grade = 4,
  sem = '1학기',
  cha = '',
  unit = '',
  tb = '',
  ctx = '',
  local = '',
  tools = [],
  stages = { C: true, R: true, E1: true, A: true, T: true, E2: true },
  options = { includeImg: true, includeCheck: true }
}) {
  const L = [];
  const P = (...lines) => L.push(...lines);

  // 과목명 추출 (여러 과목이면 융합 단원으로 표시)
  const subs = [...new Set(stds.map((x) => x.s || ''))].filter(Boolean);
  const subjName = subs.length ? subs.join('·') : '교과';

  // 활성화된 단계 목록
  const activeStages = CREATE_STAGES.filter((s) => stages[s.k]);
  const offStages = CREATE_STAGES.filter((s) => !stages[s.k]).map((s) => `${s.label || s.k}(${s.name})`);

  P(
    `# 역할과 목표`,
    `당신은 2022 개정 교육과정과 초등 교육에 정통한 수석교사이자, 전라북도교육청 지정 연구학교의 「CREATE 교수·학습 개발모형」을 적용해 수업을 설계하는 초등 교사입니다. 아래 [설계 조건]과 [CREATE 모형 규칙]을 엄격히 지켜 「CREATE 모형 기반 교수학습 지도안」 한 편을 완성해 주세요. 결과는 교사가 학교 현장에서 즉시 수정·보완하여 활용할 수 있는 완성도 높은 문서여야 합니다.`,
    ``
  );

  P(
    `# 설계 조건`,
    `- 대상 학년·학기: 초등학교 ${grade}학년 ${sem}`,
    `- 교과: ${subjName}${subs.length > 1 ? ' (여러 교과의 성취기준을 하나의 주제로 엮는 융합 단원)' : ''}`,
    `- 차시: ${cha ? cha + '차시' : '성취기준별 탐구 차시(성취기준 1개당 2~3차시) + 단원 도입 C·R 1차시 + 전이 T 1~2차시 + 단원 마무리 E(성장) 1차시를 기준으로 적절히 배당하고, 그 근거를 ① 개요 아래에 명시할 것'}`,
    `- 단원(주제)명: ${unit ? unit : '성취기준을 바탕으로 학생의 호기심과 삶을 연결하는 매력적인 주제명을 새로 지을 것'}${tb ? ` (교과서 단원: ${tb})` : ''}`,
    `- 관련 성취기준 — 2022 개정 교육과정 기준. 코드와 문장을 한 글자도 바꾸지 말고 원문 그대로 표기할 것(코드 앞자리 2·4·6은 각각 1~2, 3~4, 5~6학년군을 의미하므로 ${grade}학년 수업에 적합함):`
  );

  if (stds.length === 0) {
    P(`  (선택된 성취기준이 없습니다. ${grade}학년 ${subjName} 교육과정에 적합한 핵심 성취기준을 선정하여 작성해 주세요.)`);
  } else {
    stds.forEach((x) => {
      P(`  ${x.c} ${x.t}`);
      if (x.a) P(`    · 영역: ${x.a}`);
      if (x.act) P(`    · 교육과정 탐구 활동 예시: ${x.act}`);
      if (x.A) P(`    · 성취수준 A: ${x.A}`);
      if (x.B) P(`    · 성취수준 B: ${x.B}`);
      if (x.C) P(`    · 성취수준 C: ${x.C}`);
    });
  }

  P(
    `- 학급 실태 및 사전 진단: ${ctx ? ctx : "아직 진단 전입니다. C(진단) 단계에서 이 단원의 선수 개념, 사전 지식, 학생들의 흥미와 디지털 활용도를 확인할 진단 도구와 구체적 진단 문항(3~5문항)을 설계하고, <학습자 실태 분석>은 '진단 후 기재'로 두되 예상되는 학생 반응과 그에 따른 수업 설계 방향을 제시할 것"}`,
    ...(local ? [`- 지역·학교 맥락: ${local} — T(전이) 단계의 실천 과제 및 실생활 탐구 예시에 적극 연계할 것`] : []),
    `- 활용 가능한 AI·디지털 도구: ${tools.length ? tools.join(', ') : '웨일북, 패들렛, 캔바, 교육용 생성형 AI'}`,
    `  → 이 목록 안에서 수업 목적에 맞게 선정하고, 도구 자체가 목적이 되지 않도록 아날로그 매체(교과서, 배움공책, 모둠 활동지)와 유기적으로 결합할 것.`,
    `- 적용할 CREATE 단계: ${activeStages.map((s) => `${s.label || s.k}(${s.name})`).join(' → ')}${offStages.length ? `\n  → 단원 특성에 따라 ${offStages.join(', ')} 단계는 생략합니다. ② 설계 표에서 해당 행에 '이 단원에서는 생략함'과 타당한 사유를 명시할 것.` : ''}`,
    ``
  );

  P(
    `# CREATE 모형 규칙 (반드시 준수할 것)`,
    `CREATE는 한 차시 내에서 끝나는 수업 단계가 아니라, 단원(주제) 전체를 유기적으로 관통하는 6단계 교수·학습 설계 모형입니다. 각 차시별 지도안은 교사들에게 친숙한 [도입–전개–정리]의 흐름으로 작성합니다.`,
    `| 단계 | 의미 | ② 설계 표에 반드시 포함할 소제목 |`,
    `|---|---|---|`,
    `| C 진단 (Check & Context) | AI·디지털 도구로 학생의 흥미·강점·취약점(사전 지식, 오개념, 태도, 디지털 역량)을 입체적으로 진단해 맞춤형 배움의 출발점을 정한다 | <진단 도구 선정> <학습자 실태 분석> |`,
    `| R 탐색 (Research & Resource) | 진단 결과를 바탕으로 최적의 학습 자료를 선정하고 교육과정을 재구성하며, 핵심 일반화 문장과 탐구 질문을 수립한다 | <교육과정 수정 여부 결정> <일반화 문장 및 탐구 질문> |`,
    `| E 실행 (Experience & Engagement) | 탐구 질문의 해결을 위해 다양한 AI·디지털 도구와 아날로그 매체를 유기적으로 결합하여 학생 주도적 협력 탐구를 전개한다 | <탐구 질문 중심 탐구 활동 전개> <다양한 AI·디지털 도구 및 아날로그 매체 활용> |`,
    `| A 분석 (Assess & Adjust) | 다차원적 평가와 루브릭으로 목표 도달도를 진단하고, 미도달 학생 및 공통 오류 발생 시 R(탐색)이나 E(실행)로 되돌아가 피드백을 제공한다 | <루브릭 활용 평가 및 피드백> <환류: C·R·E로 되돌아가기> |`,
    `| T 전이 (Transfer & Transformation) | 배운 개념과 일반화 문장을 새로운 맥락(타 교과 융합, 실생활 문제, 우리 지역의 삶)에 적극 적용하여 내면화한다 | <타 교과 연계 및 실생활 적용> <지역 맥락화> |`,
    `| E 성장 (Expand & Empower) | 배움의 전 과정을 성찰하며 학생 각자의 언어로 일반화 문장을 완성하고, C(진단) 단계 결과와 비교하여 성장도를 확인·공유한다 | <일반화 문장 생성> <배움에 대한 성찰 및 진단과 평가 결과 공유> |`,
    ``
  );

  P(
    `# 문서 구조 (반드시 아래 순서와 형식을 갖출 것)`,
    `아래 5개 영역을 온전한 하나의 문서로 작성해 주세요.`,
    `① 단원 개요`,
    `  - 단원명(주제명), 대상 학년·학기, 차시 배당 및 차시별 주제`,
    `  - 단원 설정 이유 (학습자 실태 및 삶과의 연계성)`,
    `  - 관련 성취기준 및 성취수준(A·B·C)`,
    `② CREATE 6단계 단원 설계표 (마크다운 표 형식)`,
    `  - 열 구성: | 단계 | 차시 | 소제목 및 수업 활동 | 활용 자료 및 도구(★디지털 / △아날로그) | 학생 배움 질문 |`,
    `  - 단계별 소제목은 위 규칙의 필수 소제목을 반드시 포함하고, 활동 내용은 구체적으로 서술할 것.`,
    `③ 차시별 세부 지도안`,
    `  - 전 차시를 다루되, 핵심 차시는 도입-전개-정리로 매우 상세하게 작성할 것(교사의 발문과 학생의 예상 반응, 디지털 도구 활용법 상세 표기).`,
    `  - 비핵심 차시는 핵심 활동과 발문 요약을 명확히 서술할 것.`,
    `④ 평가 계획 및 루브릭`,
    `  - 평가 시기, 평가 영역 및 방법(자기평가, 동료평가, 관찰평가, 산출물 평가)`,
    `  - 성취수준 A·B·C에 따른 구체적 행동 루브릭(잘함 / 보통 / 노력 요함)`,
    `  - 환류 방안: 학생들의 오류 패턴에 따라 C/R/E 중 어느 단계로 되돌아가 어떤 보충·심화 활동을 할 것인지 명시할 것.`,
    ...(options.includeImg
      ? [
          `⑤ 시각 자료 및 그림 생성 프롬프트`,
          `  - 수업 지도안 곳곳에 그림이 필요한 자리에 인용구 형식으로 아래와 같이 표기할 것:`,
          `    > 🖼 그림 1 (제목): [상세한 그림 설명(영어나 한글로 Gemini 등 이미지 생성 모델에 입력할 수 있는 16:9 비율 프롬프트)]`,
          `  - 학생들의 이해를 돕는 개념 다이어그램, 활동 장면, 탐구 단서 그림 등 최소 2~3개의 그림 자리를 배치할 것.`
        ]
      : []),
    ``
  );

  if (options.includeCheck) {
    P(
      `# CREATE 단계별 핵심 점검 질문 (설계 시 자체 검토할 것)`,
      `- C(진단): 지식뿐 아니라 학생들의 흥미, 태도, 디지털 도구 활용 수준을 함께 진단하도록 설계했는가? 특별한 지원이 필요한 학생을 고려했는가?`,
      `- R(탐색): 진단 결과를 반영해 교육과정을 재구성했는가? 단원을 마쳤을 때 도달할 '일반화 문장'과 이를 이끄는 '탐구 질문'이 유기적인가?`,
      `- E(실행): 학생이 능동적으로 탐구 질문의 해결책을 찾는 학생 주도 활동인가? 생각과 산출물을 공유할 통로가 마련되었는가?`,
      `- A(분석): 루브릭 평가 기준이 명확한가? 어려움을 겪는 학생을 위해 R이나 E로 되돌아가는 환류(Adjust) 방안이 구체적인가?`,
      `- T(전이): 단순한 만들기나 꾸미기가 아니라, 학습한 핵심 개념을 활용해야만 해결되는 새로운 맥락(실생활, 지역 사회) 과제인가?`,
      `- E(성장): 학생이 배운 내용을 자신의 언어로 일반화할 수 있는가? C(진단) 단계와 비교해 자신의 성장을 체감할 수 있는가?`,
      ``
    );
  }

  P(
    `# 작성 지침 및 문체`,
    `- 문서는 학교 현장에서 교사가 즉시 공문서나 지도안 파일로 사용할 수 있도록 격식 있고 명료한 문체(~한다, ~함)로 작성해 주세요.`,
    `- 분량이 길어져 한 번에 출력이 어려울 경우, ①·②를 먼저 완성한 후 '이어서 ③ 차시 지도안을 작성할까요?'라고 안내해 주세요. (중간에 생략하거나 '이하 동문' 등으로 얼버무리지 말 것)`,
    `- 학생 대상 발문과 활동 안내는 ${grade}학년 학생 눈높이에 맞는 친근하고 쉬운 어휘를 사용해 주세요.`,
    `- 문서 맨 아래에는 다음 안내를 포함해 주세요:`,
    `  "※ 본 지도안은 CREATE 모형 수업 설계 도우미를 통해 생성된 AI 초안입니다. 실제 학급 상황과 학교 교육과정에 맞게 검토 후 활용해 주세요."`,
    ``,
    `# 하나의 구글 문서(Google Docs)로 만들기 위한 안내`,
    `- 문서 제목: "${grade}학년 ${subjName} CREATE 모형 기반 교수학습 지도안${unit ? ' — ' + unit : ''}"`,
    `- 제미나이(Gemini) 또는 ChatGPT에서 완성된 결과를 복사한 후, CREATE 수업 설계 도우미의 [AI 결과를 구글 문서로] 기능에 붙여 넣으면 완벽한 표 서식과 이미지 박스가 포함된 구글 문서로 즉시 변환할 수 있습니다.`,
    ``,
    `이제 위 설계 조건에 따라 완성도 높은 지도안을 작성해 주세요.`
  );

  return L.filter((x, i, a) => !(x === '' && a[i - 1] === '')).join('\n');
}
